"""Свод правил из чек-листа: python tools/rules_doc.py → docs/RULES.md (ровно то, что получает модель-оценщик)."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def render(cl: dict) -> str:
    sec = {s["id"]: s["name"] for s in cl["sections"]}
    L = [f"# Свод правил оценки — {cl['name']}, версия {cl['version']}", "",
         "Сгенерировано из `checklists/default.json` (`python tools/rules_doc.py`) — ровно то, что получает модель-оценщик. "
         "Основа — официальный чек-лист Freedom Broker; уточнения — из «Правил оценки качества работы оператора» (совместимая часть).", "",
         "## 1. Общие правила", ""]
    L += [f"{i}. {n}" for i, n in enumerate(cl["notes"], 1)]
    L += ["", "## 2. Критерии", "", "| # | Критерий | Секция | Тип ответа | Вес | N/A |", "|---|---|---|---|---|---|"]
    for i, c in enumerate(cl["criteria"], 1):
        t = {"binary": "Да / Нет", "flag": "Флаг (без баллов)"}.get(c["answer_type"]) or \
            "Шкала " + "/".join(str(s["value"]) for s in c["scale"]["steps"])
        L.append(f"| {i:02d} | {c['title']} | {sec.get(c['section_id'], '')} | {t} | {c['weight'] or '—'} | {'да' if c['na_allowed'] else 'нет'} |")
    for i, c in enumerate(cl["criteria"], 1):
        L += ["", f"### {i:02d}. {c['title']}" + (f" — {c['weight']} баллов" if c["weight"] else " — без баллов"), "",
              f"**Условие:** {c['description']}", ""]
        if c["answer_type"] == "scale":
            L += ["| Ступень | Описание |", "|---|---|"] + [f"| **{s['value']}** | {s['label']} |" for s in c["scale"]["steps"]] + [""]
        if c.get("flag_types"):
            L += ["**Виды нарушений:** " + "; ".join(f["label"] for f in c["flag_types"]) + ".", ""]
        L += [f"**N/A:** {c['na_rule']}" if c["na_allowed"] else "**N/A:** не допускается.", ""]
        if c.get("lower_if"):
            L += ["**Снижаем, если:**"] + [f"- {x}" for x in c["lower_if"]] + [""]
        if c.get("keep_if"):
            L += ["**Не снижаем, если:**"] + [f"- {x}" for x in c["keep_if"]] + [""]
    L += ["## 3. Расчёт итога", "",
          "1. N/A — только там, где разрешён и выполнено условие.",
          "2. «Да» — полный вес, «Нет» — 0; для шкалы выбирается одна ступень, верхняя ступень = полный вес (балл = ступень / максимум × вес).",
          "3. Критерии с N/A исключаются, их вес пропорционально перераспределяется между применимыми — максимум остаётся 100.",
          "4. Итог округляется до двух знаков. Если применимых критериев с весом нет — итог не рассчитывается.",
          "5. Грубые ошибки отмечаются отдельно и балл не снижают" + (" (политика чек-листа: только отметка)." if cl.get("critical_policy") != "zero_total" else " — итог обнуляется."),
          "6. «Недостаточно данных» — не отдельный статус: ответ ставится по правилам выше, обоснование начинается с «Недостаточно данных:», критерий уходит на проверку человеку.",
          "", "## 4. Как оценщик подтверждает ответ", "",
          "- Каждое снижение — с цитатой из конкретной реплики (номер реплики); цитаты сверяются с транскриптом, выдуманные отбрасываются.",
          "- Пропущенное действие — с указанием проверенного участка разговора (реплики от–до).",
          "- Для N/A — какое условие неприменимости выполнено.",
          "- Обоснование — на русском, казахском и английском.",
          "- Диалог оценивается несколькими ответами модели; по каждому критерию — голосование, расхождение отправляет критерий на проверку.", ""]
    return "\n".join(L)


if __name__ == "__main__":
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "checklists/default.json"
    out = ROOT / "docs/RULES.md"
    out.write_text(render(json.loads(src.read_text())))
    print(f"→ {out}")
